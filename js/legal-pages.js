function renderLegalPage(lang) {
  const pageId = document.body.dataset.legalPage;
  const locale = legalPageTranslations[lang] || legalPageTranslations.es;
  const page = locale.pages[pageId];
  if (!page) return;

  localStorage.setItem('jjo-lang', lang);
  document.documentElement.lang = lang;
  document.title = `${page.title} | JJO`;
  document.querySelector('meta[name="description"]')?.setAttribute('content', page.intro);

  document.querySelector('[data-legal-home]').textContent = locale.home;
  document.querySelectorAll('[data-legal-footer="desc"]').forEach((el) => {
    el.textContent = locale.footerDesc;
  });
  document.querySelector('[data-legal-footer="legal"]').textContent = locale.footerLegal;
  document.querySelector('[data-legal-footer="privacy"]').textContent = locale.footerPrivacy;
  document.querySelector('[data-legal-footer="cookies"]').textContent = locale.footerCookies;
  document.querySelector('[data-legal-footer="manage"]').textContent = locale.footerManage;

  document.querySelectorAll('.legal-lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  const sectionsHtml = page.sections.map((section) => `
    <section class="legal-section">
      <h2>${section.title}</h2>
      ${section.body.map((item) => item.trim().startsWith('<ul') ? item : `<p>${item}</p>`).join('')}
    </section>
  `).join('');

  document.getElementById('legal-content').innerHTML = `
    <div class="legal-hero">
      <p class="legal-eyebrow">${page.eyebrow}</p>
      <h1>${page.title}</h1>
      <p>${page.intro}</p>
      <div class="legal-meta">
        <span>${locale.updated}</span>
      </div>
      ${locale.warning ? `<div class="legal-warning">${locale.warning}</div>` : ''}
    </div>
    ${sectionsHtml}
  `;

  window.dispatchEvent(new CustomEvent('jjo:language-changed', { detail: { lang } }));
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('[data-legal-year]').forEach((el) => {
    el.textContent = new Date().getFullYear();
  });

  document.querySelectorAll('.legal-lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => renderLegalPage(btn.dataset.lang));
  });

  renderLegalPage(localStorage.getItem('jjo-lang') || 'es');
});
