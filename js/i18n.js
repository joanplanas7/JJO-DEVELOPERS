function applyMetaTranslations(lang) {
  const map = translations[lang];
  const titleEl = document.querySelector('[data-i18n-meta="title"]');
  const descriptionEl = document.querySelector('[data-i18n-meta="description"]');
  const ogTitleEl = document.querySelector('[data-i18n-meta="og:title"]');
  const ogDescriptionEl = document.querySelector('[data-i18n-meta="og:description"]');
  const schemaDescriptionEl = document.querySelector('[data-i18n-meta="schema:description"]');

  if (titleEl && map['meta.title']) {
    titleEl.textContent = map['meta.title'];
  }
  if (descriptionEl && map['meta.description']) {
    descriptionEl.setAttribute('content', map['meta.description']);
  }
  if (ogTitleEl && map['meta.ogTitle']) {
    ogTitleEl.setAttribute('content', map['meta.ogTitle']);
  }
  if (ogDescriptionEl && map['meta.ogDescription']) {
    ogDescriptionEl.setAttribute('content', map['meta.ogDescription']);
  }
  if (schemaDescriptionEl && map['meta.schemaDescription']) {
    const schema = JSON.parse(schemaDescriptionEl.textContent);
    schema.description = map['meta.schemaDescription'];
    schemaDescriptionEl.textContent = JSON.stringify(schema, null, 2);
  }
}

function setLanguage(lang) {
  if (!translations[lang]) return;

  localStorage.setItem('jjo-lang', lang);
  document.documentElement.lang = lang;
  window.dispatchEvent(new CustomEvent('jjo:language-changed', { detail: { lang } }));

  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (translations[lang][key] !== undefined) {
      el.innerHTML = translations[lang][key];
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (translations[lang][key] !== undefined) {
      el.placeholder = translations[lang][key];
    }
  });

  applyMetaTranslations(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => setLanguage(btn.dataset.lang));
  });

  const saved = localStorage.getItem('jjo-lang') || 'es';
  setLanguage(saved);
});
